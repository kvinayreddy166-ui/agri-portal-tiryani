/**
 * Check if a raw pest string matches a target query or canonical pest name.
 */
function matchesPest(rawPest: string, selectedPest: string): boolean {
  if (!selectedPest) return true;
  const normSelected = selectedPest.trim().toLowerCase();
  const normRaw = rawPest.trim().toLowerCase();

  if (normRaw === normSelected) return true;

  const canonical = CANONICAL_PEST_DEFINITIONS.find(
    (c) => c.name.toLowerCase() === normSelected || c.id.toLowerCase() === normSelected
  );

  if (canonical) {
    if (canonical.matcher) {
      return canonical.matcher(rawPest);
    }
    return canonical.pattern.test(rawPest);
  }

  return normRaw.includes(normSelected) || normSelected.includes(normRaw);
}

/**
 * Get sorted unique, deduplicated canonical pests for a chosen crop.
 */
export function getPestListForCrop(
  entries: CropPestInsecticideEntry[],
  crop: string
): Array<{ name: string; nameTe: string; count: number }> {
  const map = new Map<string, { name: string; nameTe: string; count: number }>();
  const normalizedCrop = crop.trim().toLowerCase();

  const cropEntries = normalizedCrop
    ? entries.filter((e) => e.crop.trim().toLowerCase() === normalizedCrop)
    : entries;

  for (const entry of cropEntries) {
    const rawPest = entry.pest;
    let matchedCanonical = false;

    for (const def of CANONICAL_PEST_DEFINITIONS) {
      if (def.excludedCrops?.some((ec) => normalizedCrop.includes(ec))) {
        continue;
      }
      const isMatch = def.matcher ? def.matcher(rawPest) : def.pattern.test(rawPest);
      if (isMatch) {
        matchedCanonical = true;
        const existing = map.get(def.name);
        if (existing) {
          existing.count++;
        } else {
          map.set(def.name, {
            name: def.name,
            nameTe: def.nameTe,
            count: 1,
          });
        }
      }
    }

    if (!matchedCanonical) {
      // Clean trailing commas, punctuation and spaces from raw label
      const cleanPest = rawPest.replace(/^[\s,./;()-]+|[\s,./;()-]+$/g, '').trim();
      if (cleanPest && cleanPest.length > 2) {
        const existing = map.get(cleanPest);
        if (existing) {
          existing.count++;
        } else {
          map.set(cleanPest, {
            name: cleanPest,
            nameTe: entry.pestTe || cleanPest,
            count: 1,
          });
        }
      }
    }
  }

  return Array.from(map.values()).sort((a, b) => b.count - a.count);
}

/**
 * Get available IRAC groups for the selected crop & pest.
 */
export function getAvailableIracGroups(
  entries: CropPestInsecticideEntry[],
  crop?: string,
  pest?: string
): Array<{ group: string; name: string; count: number }> {
  const map = new Map<string, { group: string; name: string; count: number }>();
  const normCrop = crop?.trim().toLowerCase();

  for (const entry of entries) {
    if (normCrop && entry.crop.trim().toLowerCase() !== normCrop) continue;
    if (pest && !matchesPest(entry.pest, pest)) continue;

    const grp = entry.iracGroup || 'Other';
    const existing = map.get(grp);
    if (existing) {
      existing.count++;
    } else {
      map.set(grp, {
        group: grp,
        name: entry.moaGroupName || grp,
        count: 1,
      });
    }
  }

  return Array.from(map.values()).sort((a, b) => a.group.localeCompare(b.group));
}

/**
 * Filter crop-pest insecticide entries based on selected crop, pest, query, IRAC group, and toxicity.
 */
export function filterCropPestInsecticides(
  entries: CropPestInsecticideEntry[],
  options: CropPestFilterOptions
): CropPestInsecticideEntry[] {
  const query = options.query.trim().toLowerCase();
  const crop = options.crop.trim().toLowerCase();
  const pest = options.pest.trim();
  const irac = options.iracGroup?.trim();
  const toxicity = options.toxicityBand;

  return entries.filter((entry) => {
    // 1. Crop filter
    if (crop && crop !== '' && entry.crop.toLowerCase() !== crop) {
      return false;
    }

    // 2. Pest filter (smart canonical matching across all variations)
    if (pest && pest !== '' && !matchesPest(entry.pest, pest)) {
      return false;
    }

    // 3. IRAC Group filter
    if (irac && irac !== 'all' && irac !== '') {
      if (entry.iracGroup !== irac) {
        return false;
      }
    }

    // 4. Toxicity Band filter
    if (toxicity && toxicity !== 'all') {
      if (entry.toxicityBand !== toxicity) {
        return false;
      }
    }

    // 5. Text search query
    if (query) {
      const insMatch =
        entry.insecticide.toLowerCase().includes(query) ||
        entry.insecticideTe.toLowerCase().includes(query);
      const brandsMatch = entry.popularBrands.some((b) => b.toLowerCase().includes(query));
      const moaMatch =
        entry.iracGroup.toLowerCase().includes(query) ||
        entry.moaGroupName.toLowerCase().includes(query) ||
        entry.moaDescription.toLowerCase().includes(query);
      const pestMatch =
        entry.pest.toLowerCase().includes(query) ||
        entry.pestTe.toLowerCase().includes(query);
      const cropMatch =
        entry.crop.toLowerCase().includes(query) ||
        entry.cropTe.toLowerCase().includes(query);
      const familyMatch =
        entry.chemicalFamily.toLowerCase().includes(query) ||
        entry.chemicalFamilyTe.toLowerCase().includes(query);

      if (!insMatch && !brandsMatch && !moaMatch && !pestMatch && !cropMatch && !familyMatch) {
        return false;
      }
    }

    return true;
  });
}

