import { type AgrochemicalItem, type AgrochemicalCategory, type AgrochemicalFilterOptions } from '../types';

/**
 * Filter agrochemical items based on search query, category, and initial letter.
 */
export function filterAgrochemicals(
  items: AgrochemicalItem[],
  options: AgrochemicalFilterOptions
): AgrochemicalItem[] {
  const query = options.query.trim().toLowerCase();
  const category = options.category;
  const letter = options.letter.trim().toUpperCase();

  return items.filter((item) => {
    // 1. Category Filter
    if (category !== 'all' && item.category !== category) {
      return false;
    }

    // 2. Letter Filter (A-Z)
    if (letter && letter !== '') {
      const firstChar = item.name.trim().charAt(0).toUpperCase();
      if (firstChar !== letter) {
        return false;
      }
    }

    // 3. Search Query Filter
    if (query) {
      const nameMatch = item.name.toLowerCase().includes(query) || item.nameTe.toLowerCase().includes(query);
      const brandsMatch = item.popularBrands.some((b) => b.toLowerCase().includes(query));
      const moaMatch =
        item.moaGroup.toLowerCase().includes(query) ||
        item.moaGroupName.toLowerCase().includes(query) ||
        item.moaDescription.toLowerCase().includes(query);
      const familyMatch = item.chemicalFamily.toLowerCase().includes(query) || item.chemicalFamilyTe.toLowerCase().includes(query);
      const cropMatch = item.targetCrops.some((c) => c.toLowerCase().includes(query)) || item.targetCropsTe.some((c) => c.toLowerCase().includes(query));
      const pestMatch = item.targetPests.some((p) => p.toLowerCase().includes(query)) || item.targetPestsTe.some((p) => p.toLowerCase().includes(query));

      if (!nameMatch && !brandsMatch && !moaMatch && !familyMatch && !cropMatch && !pestMatch) {
        return false;
      }
    }

    return true;
  }).sort((a, b) => a.name.localeCompare(b.name));
}

/**
 * Calculate item counts per category.
 */
export function getCategoryCounts(items: AgrochemicalItem[]): Record<AgrochemicalCategory, number> {
  const counts: Record<AgrochemicalCategory, number> = {
    all: items.length,
    insecticide: 0,
    fungicide: 0,
    weedicide: 0,
    fertilizer: 0,
  };

  for (const item of items) {
    if (counts[item.category] !== undefined) {
      counts[item.category]++;
    }
  }

  return counts;
}

/**
 * Get list of available first letters from the dataset.
 */
export function getAvailableLetters(items: AgrochemicalItem[]): string[] {
  const set = new Set<string>();
  for (const item of items) {
    const char = item.name.trim().charAt(0).toUpperCase();
    if (char >= 'A' && char <= 'Z') {
      set.add(char);
    }
  }
  return Array.from(set).sort();
}

/**
 * Generate formatted WhatsApp advisory text for an agrochemical product.
 */
export function buildWhatsAppAdvisory(
  item: AgrochemicalItem,
  t: (en: string, te: string) => string
): string {
  const isFertilizer = item.category === 'fertilizer';
  const lines: string[] = [
    `🧪 *${t('AGRONIX — Agrochemical Advisory', 'అగ్రోనిక్స్ — వ్యవసాయ రసాయన సలహా')}*`,
    `🔬 *${t('Chemical', 'రసాయనం')}:* *${item.name}* (${item.nameTe})`,
    `🏷️ *${t('Category', 'వర్గం')}:* ${t(item.category.toUpperCase(), item.categoryTe)}`,
  ];

  if (item.popularBrands.length > 0) {
    lines.push(`🏪 *${t('Popular Brands', 'ప్రసిద్ధ బ్రాండ్లు')}:* ${item.popularBrands.join(', ')}`);
  }

  lines.push(
    `⚡ *${t('Mode of Action / Group', 'రసాయన గ్రూప్ / MoA')}:* ${item.moaGroup} — ${item.moaGroupName}`,
    `🌿 *${t('Target Crops', 'సిఫార్సు పంటలు')}:* ${item.targetCrops.join(', ')}`,
    `🎯 *${isFertilizer ? t('Target Deficiency', 'పోషక లోపం') : t('Target Pests/Diseases/Weeds', 'నివారించే తెగుళ్లు/పురుగులు')}:* ${item.targetPests.join(', ')}`,
    `📏 *${t('Dosage per Acre', 'ఎకరాకు మోతాదు')}:* *${item.dosagePerAcre}*`,
    `💧 *${t('Dosage per Litre', 'లీటరుకు మోతాదు')}:* ${item.dosagePerLitre}`
  );

  if (!isFertilizer && item.waitingPeriodDays !== 'N/A') {
    lines.push(`⏳ *${t('Waiting Period (PHI)', 'కోతకు నిరీక్షణ కాలం')}:* ${item.waitingPeriodDays} ${t('days', 'రోజులు')}`);
    lines.push(`⚠️ *${t('Toxicity Band', 'విష తీవ్రత')}:* ${item.toxicityLabel}`);
  }

  if (item.fcoSpecification) {
    lines.push(`📋 *${t('FCO Standard', 'FCO ప్రమాణాలు')}:* ${item.fcoSpecification}`);
  }

  lines.push('');
  lines.push(`⚠️ *${t('Precaution', 'ముందుజాగ్రత్త')}:* ${item.sprayPrecautions}`);
  lines.push('');
  lines.push(`_Generated by AGRONIX Agrochemicals Database — Tiryani Mandal_`);

  return lines.join('\n');
}
