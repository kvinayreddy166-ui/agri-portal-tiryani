def translate_pest(p_en):
    p_lower = p_en.lower()
    matched_te = []
    for pat, te in PEST_KEYWORD_TE:
        import re
        if re.search(pat, p_lower):
            matched_te.append(te)
    if matched_te:
        return ", ".join(list(dict.fromkeys(matched_te))[:2])
    return p_en

